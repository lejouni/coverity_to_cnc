# -*- coding: utf-8 -*-
#
# Writes the flat per-stream report to CSV.
#
import logging
import os


def writeCsv(report_data, output_dir, filename):
    path = os.path.join(output_dir, filename)
    with open(path, "w", newline="", encoding="utf-8") as f:
        version = report_data.get("version")
        generated_at = report_data.get("generated_at")
        if version or generated_at:
            f.write(f"# Generated by coverity_to_cnc v{version or '?'} on {generated_at or '?'}\n")
        report_data["streams"].to_csv(f, index=False)
    logging.info(f"Wrote CSV report: {path}")
    return path
